// Writes the theme presets in resources/themes that are modelled on the themes of RogueOpus:
// each of those is one foreground colour on one background colour. Run with `node scripts/generate-themes.js`.
// The other presets in that folder (dimmed, monochrome) are written by hand and are left alone.
const fs = require('fs');
const path = require('path');

const OUT_DIR = path.join(__dirname, '..', 'resources', 'themes');

// name: [foreground, background, accent]. The first two are the pair of the RogueOpus theme with that name,
// the accent is a colour of the same family from its palette
const THEMES = {
  'mono-blue': [[200, 200, 200], [8, 32, 40], [51, 150, 150]],
  'midnight-purple': [[242, 172, 200], [4, 8, 20], [255, 149, 203]],
  'white-not': [[91, 94, 131], [200, 200, 200], [91, 94, 131]],
  'gray-not': [[120, 91, 131], [153, 153, 153], [120, 91, 131]],
  'paper-pink': [[54, 97, 91], [242, 172, 200], [54, 97, 91]],
  classic: [[200, 200, 200], [10, 10, 10], [51, 153, 255]],
  alien: [[0, 204, 0], [10, 10, 10], [0, 204, 0]],
  'alien-2': [[0, 204, 0], [35, 35, 35], [102, 255, 102]],
  pastel: [[149, 255, 164], [4, 16, 20], [149, 255, 164]],
  murder: [[255, 90, 102], [200, 200, 200], [255, 51, 51]],
};

const BLACK = [0, 0, 0];
const WHITE = [255, 255, 255];

const mix = (a, b, amount) => a.map((v, i) => Math.round(v + (b[i] - v) * amount));
const rgb = (c) => `rgb(${c.join(', ')})`;

function luminance(c) {
  const [r, g, b] = c.map((v) => {
    const s = v / 255;
    return s <= 0.03928 ? s / 12.92 : Math.pow((s + 0.055) / 1.055, 2.4);
  });
  return 0.2126 * r + 0.7152 * g + 0.0722 * b;
}

function contrast(a, b) {
  const [hi, lo] = [luminance(a), luminance(b)].sort((x, y) => y - x);
  return (hi + 0.05) / (lo + 0.05);
}

/** Moves a colour away from the background until text in it can be read comfortably */
function readable(color, background, towards, minContrast) {
  let result = color;
  for (let i = 0; i < 20 && contrast(result, background) < minContrast; i++) {
    result = mix(result, towards, 0.1);
  }
  return result;
}

function createTheme(name, [fore, back, accentBase]) {
  const isDark = luminance(back) < 0.2;
  const away = isDark ? WHITE : BLACK;
  const text = readable(fore, back, away, 5);
  const accent = readable(accentBase, back, away, 3);
  // Panels are a step away from the background, inputs and borders two steps:
  // darker, except where the background is nearly black already
  const isNearBlack = Math.max(...back) < 24;
  const shade = (amount) => (isNearBlack ? mix(back, fore, amount) : mix(back, BLACK, amount));
  const shade1 = shade(isNearBlack ? 0.09 : isDark ? 0.28 : 0.07);
  const shade2 = shade(isNearBlack ? 0.16 : isDark ? 0.45 : 0.15);

  const vars = {
    'text-color': text,
    'text-color-alt': back,
    'text-color-muted': mix(text, back, 0.45),
    'text-color-strong': mix(text, away, 0.5),
    'background-color': back,
    'background-color-alt': mix(back, isDark ? fore : WHITE, isDark ? 0.05 : 0.18),
    'background-color-selected': mix(back, accent, 0.35),
    shade1,
    shade2,
    'titlebar-background-color': shade2,
    'titlebar-background-color-alt': shade1,
    'titlebar-color': mix(text, back, 0.4),
    'accent-color': accent,
  };

  const label = name.replace(/-/g, ' ');
  const lines = [
    `/* ${label[0].toUpperCase()}${label.slice(1)}: after the theme of the same name in RogueOpus.`,
    '   It looks the same whether the colour scheme is set to light or dark.',
    '   Generated by scripts/generate-themes.js */',
    '.dark,',
    '.light {',
    ...Object.entries(vars).map(([key, value]) => `  --${key}: ${rgb(value)};`),
    '}',
    '',
  ];
  return lines.join('\n');
}

for (const [name, colors] of Object.entries(THEMES)) {
  const file = path.join(OUT_DIR, `${name}.css`);
  fs.writeFileSync(file, createTheme(name, colors));
  console.log('wrote', path.relative(process.cwd(), file));
}
